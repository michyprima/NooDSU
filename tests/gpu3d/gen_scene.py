#!/usr/bin/env python3
# Turns a dump of one frame's polygons from the Mac harness into scene.h: raw clip coordinates, attributes and vertex colors
# Usage: gen_scene.py <dump> <scene.h>
# The dump is little-endian words: 48 of registers and counts, then 22 per polygon (attributes, size and texture format, then
# X, Y, Z, W and color for up to 4 vertices), written by the polygon setup before clipping
import struct, sys

data = open(sys.argv[1], 'rb').read()
words = struct.unpack('<%dI' % (len(data) // 4), data)
disp, clear, depth, fogColor, fogOffset, _, count, viewport = words[:8]
fog, edge = words[8:40], words[40:48]
polygons = []
for i in range(count):
    record = words[48 + i * 22:48 + (i + 1) * 22]
    attr, info = record[0], record[1]
    size, fmt = info & 0xFF, (info >> 8) & 0xFF
    # Only polygons that were solid in the game; textures aren't replayed, so anything their alpha made translucent is dropped
    if ((attr >> 16) & 0x1F) != 31 or fmt in (1, 6): continue
    polygons.append((attr, size, record[2:2 + size * 5]))

with open(sys.argv[2], 'w') as out:
    print('// Generated by gen_scene.py from one frame of a game: only polygon coordinates, no textures', file=out)
    print(f'#define SCENE_DISP3DCNT 0x{disp:04X}', file=out)
    print(f'#define SCENE_CLEAR_COLOR 0x{clear:08X}', file=out)
    print(f'#define SCENE_CLEAR_DEPTH 0x{depth:04X}', file=out)
    print(f'#define SCENE_FOG_COLOR 0x{fogColor:08X}', file=out)
    print(f'#define SCENE_FOG_OFFSET 0x{fogOffset:04X}', file=out)
    print(f'#define SCENE_POLYGONS {len(polygons)}', file=out)
    print('static const unsigned char sceneFog[32] = { ' + ', '.join(map(str, fog)) + ' };', file=out)
    print('static const unsigned short sceneEdge[8] = { ' + ', '.join(map(str, edge)) + ' };', file=out)
    print('static const struct { unsigned attr, size, v[20]; } scene[] = {', file=out)
    for attr, size, v in polygons:
        print(f'    {{ 0x{attr:08X}, {size}, {{ ' + ', '.join(f'0x{x:X}' for x in v) + ' } },', file=out)
    print('};', file=out)
print(f'{len(polygons)} of {count} polygons, viewport {viewport:08X}, DISP3DCNT {disp:04X}')
